function table(widths, rows, headerFill = 'F3E3C8') {
  const border = { style: BorderStyle.SINGLE, size: 4, color: 'BFBFBF' };
  const borders = { top: border, bottom: border, left: border, right: border };
  return new Table({
    width: { size: widths.reduce((a, c) => a + c, 0), type: WidthType.DXA },
    columnWidths: widths,
    rows: rows.map((row, ri) => new TableRow({
      tableHeader: ri === 0,
      children: row.map((cell, ci) => new TableCell({
        width: { size: widths[ci], type: WidthType.DXA },
        borders,
        margins: { top: 60, bottom: 60, left: 90, right: 90 },
        shading: ri === 0 ? { type: ShadingType.CLEAR, color: 'auto', fill: headerFill } : undefined,
        children: String(cell).split('\n').map(line => new Paragraph({
          spacing: { after: 20 },
          children: [new TextRun({ text: line, font: FONT, size: 19, bold: ri === 0 })],
        })),
      })),
    })),
  });
}

