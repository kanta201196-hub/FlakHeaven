def gantt(width):
    # окно: 19.10.2026 – 16.05.2027
    d0, d1 = date(2026, 10, 19), date(2027, 5, 17)
    span = (d1 - d0).days
    lab_w = 120
    W, rowh = width, 15
    bars = [
        ("Сборка 3.5 и правки теста", "3.5", date(2026, 10, 19), date(2026, 11, 2)),
        ("Steamworks, взнос, страница", "Steam", date(2026, 10, 19), date(2026, 11, 30)),
        ("Вертикальный срез биома 1", "Срез", date(2026, 11, 2), date(2026, 12, 28)),
        ("Демо и подготовка к фесту", "Демо", date(2026, 12, 28), date(2027, 2, 22)),
        ("Steam Next Fest", "Фест", date(2027, 2, 22), date(2027, 3, 2)),
        ("Биом 2 и контент РД", "РД", date(2026, 12, 28), date(2027, 4, 5)),
        ("Музыка и звук", "Муз", date(2026, 11, 2), date(2027, 4, 5)),
        ("Релиз раннего доступа", "РД", date(2027, 4, 5), date(2027, 5, 17)),
    ]
    H = 30 + rowh * len(bars) + 10
    dr = Drawing(W, H)
    x = lambda d: lab_w + (W - lab_w) * (d - d0).days / span
    months = [(date(2026, 10, 19), "окт"), (date(2026, 11, 1), "ноя"), (date(2026, 12, 1), "дек"),
              (date(2027, 1, 1), "янв"), (date(2027, 2, 1), "фев"), (date(2027, 3, 1), "мар"),
              (date(2027, 4, 1), "апр"), (date(2027, 5, 1), "май")]
    top = H - 14
    for md, nm in months:
        dr.add(Line(x(md), 6, x(md), top + 4, strokeColor=LINE, strokeWidth=0.5))
        dr.add(String(x(md) + 2, top, nm, fontName="DV", fontSize=7, fillColor=MUTED))
    for i, (nm, ph, a, b) in enumerate(bars):
        y = top - 16 - i * rowh
        dr.add(String(0, y + 3, nm, fontName="DV", fontSize=7.5, fillColor=INK))
        dr.add(Rect(x(a), y, max(3, x(b) - x(a)), 10, fillColor=PH[ph], strokeColor=None))
    for md, nm in [(date(2026, 11, 30), "страница"), (date(2026, 12, 20), "срез"),
                   (date(2027, 2, 22), "фест"), (date(2027, 4, 26), "РД")]:
        dr.add(Line(x(md), 6, x(md), top - 4, strokeColor=ACC, strokeWidth=0.8, strokeDashArray=[2, 2]))
        dr.add(String(x(md) + 2, 0, nm, fontName="DVB", fontSize=6.5, fillColor=ACC))
    return dr


